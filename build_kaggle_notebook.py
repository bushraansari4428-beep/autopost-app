                "    def chunked_dispatch_attention_fn(query, key, value, attn_mask=None, chunk_size=128, **kwargs):\n",
                "        if query.ndim >= 3 and query.shape[1] > chunk_size:\n",
                "            seq_len_q = query.shape[1]\n",
                "            out_chunks = []\n",
                "            for i in range(0, seq_len_q, chunk_size):\n",
